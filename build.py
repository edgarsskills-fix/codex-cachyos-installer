#!/usr/bin/env python3
"""Repack the pinned local DEB without copying any installed user data."""
import argparse
import hashlib
import io
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import tarfile
import zipfile

ROOT = Path(__file__).resolve().parent
DEPENDENCIES = [
    'alsa-lib', 'at-spi2-core', 'cairo', 'libcups', 'dbus', 'expat',
    'mesa', 'libgcc', 'gdk-pixbuf2', 'libglvnd', 'glib2', 'glibc',
    'gtk3', 'libnotify', 'nspr', 'nss', 'pango', 'libstdc++',
    'libssl.so=3-64', 'libcrypto.so=3-64', 'tpm2-tss', 'systemd-libs',
    'libusb', 'libx11', 'libxcb', 'libxcomposite', 'libxdamage',
    'libxext', 'libxfixes', 'libxkbcommon', 'libxrandr', 'libdrm',
    'vulkan-icd-loader', 'xdg-utils', 'xz', 'desktop-file-utils',
]


def digest(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        while block := f.read(4 * 1024 * 1024):
            h.update(block)
    return h.hexdigest()


def run(*args, **kwargs):
    print('+', shlex.join(map(str, args)), flush=True)
    subprocess.run(list(map(str, args)), check=True, **kwargs)


def control_fields(path):
    raw = subprocess.check_output(['ar', 'p', str(path), 'control.tar.xz'])
    with tarfile.open(fileobj=io.BytesIO(raw), mode='r:xz') as archive:
        text = archive.extractfile('./control').read().decode()
    return dict(line.split(': ', 1) for line in text.splitlines()
                if line and not line[0].isspace() and ': ' in line)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--deb', type=Path, required=True)
    parser.add_argument('--reuse-package', action='store_true',
                        help='Reuse the existing pinned package while iterating on the GUI')
    args = parser.parse_args()
    deb = args.deb.resolve(strict=True)
    metadata = json.loads((ROOT / 'source.json').read_text())
    if digest(deb) != metadata['sha256']:
        raise SystemExit('The DEB does not match the pinned SHA-256 in source.json')
    fields = control_fields(deb)
    for key, expected in [('Package', 'chatgpt'), ('Version', metadata['version']),
                          ('Architecture', 'amd64')]:
        if fields.get(key) != expected:
            raise SystemExit(f'Unexpected {key}: {fields.get(key)}')
    version = metadata['version']
    build = ROOT / 'build'
    build.mkdir(exist_ok=True)
    packages = build / 'packages'
    packages.mkdir(exist_ok=True)
    source = build / 'chatgpt.deb'
    if source.is_symlink():
        source.unlink()
    if source.exists():
        raise SystemExit(f'Remove the unexpected regular file {source}')
    source.symlink_to(deb)
    shutil.copy2(ROOT / 'chatgpt.install', build / 'chatgpt.install')
    depends = ' '.join(shlex.quote(d) for d in DEPENDENCIES)
    (build / 'PKGBUILD').write_text(f'''# Generated by build.py; application files are not patched.
pkgname=chatgpt
pkgver={version}
pkgrel=1
pkgdesc='ChatGPT / Codex desktop app (local DEB repacked for CachyOS and Arch)'
arch=('x86_64')
url='https://developers.openai.com/codex/app'
license=('custom')
depends=({depends})
optdepends=('git: coding projects')
options=('!strip' '!debug')
backup=('etc/apparmor.d/chatgpt')
install=chatgpt.install
source=('chatgpt.deb')
noextract=('chatgpt.deb')
sha256sums=('{metadata['sha256']}')
package() {{
    ar p "$srcdir/chatgpt.deb" data.tar.xz | bsdtar -xpJf - -C "$pkgdir"
}}
''')
    config = build / 'makepkg.conf'
    config.write_text('source /etc/makepkg.conf\nCOMPRESSZST=(zstd -c -T2 -6 -)\n')
    env = os.environ.copy()
    env['PKGDEST'] = str(packages)
    package = packages / f'chatgpt-{version}-1-x86_64.pkg.tar.zst'
    if not (args.reuse_package and package.is_file()):
        run('makepkg', '--config', config, '--nodeps', '--nocheck', '--force',
            cwd=build, env=env)
    else:
        run('pacman', '-Qp', package)
    package_hash = digest(package)
    dist = ROOT / 'dist'
    dist.mkdir(exist_ok=True)
    bundle_name = f'ChatGPT-Codex-CachyOS-{version}-x86_64'
    bundle = dist / bundle_name
    bundle.mkdir(exist_ok=True)
    shutil.copyfile(package, bundle / package.name)
    # Only this generated header binds the executable to its adjacent package.
    (build / 'bundle.h').write_text(
        f'#define APP_VERSION "{version}"\n'
        f'#define PACKAGE_FILE "{package.name}"\n'
        f'#define PACKAGE_SHA256 "{package_hash}"\n')
    flags = subprocess.check_output(
        ['pkg-config', '--cflags', '--libs', 'gtk4', 'libadwaita-1', 'gio-unix-2.0'],
        text=True).split()
    run('gcc', '-std=c11', '-O2', '-march=x86-64', '-mtune=generic',
        '-Wall', '-Wextra', '-Werror', '-Wformat=2', '-Werror=format-security',
        '-fstack-protector-strong', '-D_FORTIFY_SOURCE=3', '-Wl,-z,relro,-z,now',
        '-I', build, ROOT / 'src/installer.c', '-o', bundle / 'Установить', *flags)
    shutil.copyfile(ROOT / 'bundle-readme.md', bundle / 'ПРОЧИТАЙ.md')
    manifest = {**metadata, 'arch_package': package.name,
                'arch_package_sha256': package_hash,
                'installer_sha256': digest(bundle / 'Установить')}
    (bundle / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    files = sorted(p for p in bundle.iterdir() if p.is_file() and p.name != 'SHA256SUMS.txt')
    (bundle / 'SHA256SUMS.txt').write_text(
        ''.join(f'{digest(p)}  {p.name}\n' for p in files))
    # Unix executable mode is retained by GNOME Archive Manager when extracting ZIP.
    archive_path = dist / f'{bundle_name}.zip'
    with zipfile.ZipFile(archive_path, 'w', compression=zipfile.ZIP_STORED) as z:
        for p in sorted(bundle.iterdir()):
            z.write(p, arcname=f'{bundle_name}/{p.name}')
    (dist / 'SHA256SUMS.txt').write_text(
        f'{digest(archive_path)}  {archive_path.name}\n')
    print('Archive:', archive_path)
    print('SHA-256:', digest(archive_path))


if __name__ == '__main__':
    main()
